import { useRef, useState } from "react";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { getErrorMessage } from "~/lib/rephi";
import { ErrorAlert, Modal } from "~/components/react";
import { adminKeys, usersApi } from "~/lib/api/admin";
import type { UserWithGrants } from "~/types/admin.types";

interface ResetPasswordModalProps {
  user: UserWithGrants;
  onClose: () => void;
}

export default function ResetPasswordModal({ user, onClose }: ResetPasswordModalProps) {
  const queryClient = useQueryClient();
  const inputRef = useRef<HTMLInputElement>(null);
  const [copied, setCopied] = useState<"yes" | "manual" | null>(null);

  const reset = useMutation({
    mutationFn: () => usersApi.resetPassword(user.id),
    onSuccess: () => queryClient.invalidateQueries({ queryKey: adminKeys.users }),
  });

  const temporaryPassword = reset.data?.temporary_password;

  const copy = async () => {
    if (!temporaryPassword) return;
    try {
      await navigator.clipboard.writeText(temporaryPassword);
      setCopied("yes");
    } catch {
      // No clipboard on plain HTTP or without permission: select it instead.
      inputRef.current?.select();
      setCopied("manual");
    }
  };

  return (
    <Modal isOpen onClose={onClose} title={`Reset the password of ${user.email}`}>
      {temporaryPassword ? (
        <div data-testid="temporary-password-panel">
          <div className="rounded-md bg-yellow-50 border border-yellow-300 p-4 mb-4" role="alert">
            <p className="text-sm text-yellow-900 font-medium">Copy this password now: it will not be shown again.</p>
            <p className="text-sm text-yellow-900 mt-1">
              Give it to {user.email} through a safe channel. It only lets them sign in and choose a new
              password; their other sessions have been closed.
            </p>
          </div>
          <label htmlFor="temporary-password" className="block text-sm font-medium mb-2 text-gray-500">
            Temporary password
          </label>
          <div className="flex gap-2">
            <input
              ref={inputRef}
              id="temporary-password"
              readOnly
              value={temporaryPassword}
              onFocus={(event) => event.target.select()}
              className="flex-1 border rounded px-3 py-2 font-mono text-gray-900 bg-gray-50"
              data-testid="temporary-password"
            />
            <button
              type="button"
              onClick={copy}
              className="bg-blue-600 text-white px-4 py-2 rounded hover:bg-blue-700"
            >
              Copy
            </button>
          </div>
          {copied === "yes" && <p className="mt-2 text-sm text-green-700">Copied to the clipboard.</p>}
          {copied === "manual" && (
            <p className="mt-2 text-sm text-gray-600">The clipboard is not available: the password is selected, copy it.</p>
          )}
          <div className="flex justify-end mt-6">
            <button type="button" onClick={onClose} className="px-4 py-2 border rounded hover:bg-gray-50 text-gray-700">
              Done
            </button>
          </div>
        </div>
      ) : (
        <div>
          <ErrorAlert message={reset.error ? getErrorMessage(reset.error, "Error resetting the password") : null} />
          <p className="text-gray-700 mb-2">
            {user.email} gets a new temporary password, generated by the server and shown to you once.
          </p>
          <ul className="list-disc pl-5 text-sm text-gray-600 mb-6 space-y-1">
            <li>Their current password stops working.</li>
            <li>Every session they have open ends, on every device.</li>
            <li>After signing in with the temporary password they must choose a new one.</li>
          </ul>
          <div className="flex justify-end gap-2">
            <button type="button" onClick={onClose} className="px-4 py-2 border rounded hover:bg-gray-50 text-gray-700">
              Cancel
            </button>
            <button
              type="button"
              onClick={() => reset.mutate()}
              disabled={reset.isPending}
              className="bg-red-600 text-white px-4 py-2 rounded hover:bg-red-700 disabled:opacity-50"
            >
              {reset.isPending ? "Resetting..." : "Reset password"}
            </button>
          </div>
        </div>
      )}
    </Modal>
  );
}
